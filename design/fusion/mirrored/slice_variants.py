"""Slice the independent mirrored parts; never overwrite original print outputs."""
from pathlib import Path
import json,hashlib,subprocess,re,zipfile,concurrent.futures,shutil,sys
P=Path(__file__).resolve().parent
EXE='/Applications/Original Prusa Drivers/PrusaSlicer.app/Contents/MacOS/PrusaSlicer'
profile=P.parent/'print/mk3s-petg-06.ini'
parts=json.loads((P/'print-export.json').read_text())['parts']
selected=sys.argv[1:]
parts=[r for r in parts if not selected or r['path'] in selected]

def check(row):
 name=row['path'];support='shell' in name or name.endswith('cap')
 gcode=Path('/tmp/midi-mirrored-'+name.replace('/','-')+'.gcode')
 common=[EXE,'--datadir','/tmp/midi-mirrored-slicer','--load',str(profile),'--support-material' if support else '--no-support-material','--center','125,105','--threads','2']
 q=subprocess.run(common+['--export-gcode','--output',str(gcode),str(P/(name+'.stl'))],capture_output=True,text=True)
 Path('/tmp/midi-mirrored-'+name.replace('/','-')+'.log').write_text(q.stdout+q.stderr)
 if q.returncode:raise RuntimeError(name+'\n'+q.stdout+q.stderr)
 text=gcode.read_text();assert '; nozzle_diameter = 0.6' in text
 result={'part':name,'STL_sha256':hashlib.sha256((P/(name+'.stl')).read_bytes()).hexdigest(),'gcode_sha256':hashlib.sha256(gcode.read_bytes()).hexdigest(),'slice_exit_code':0,'support_enabled':support}
 for pattern,label in [(r'estimated printing time \(normal mode\) = (.*)','estimated_time'),(r'filament used \[g\] = (.*)','filament_g')]:
  m=re.search(pattern,text);result[label]=m.group(1) if m else None
 amount=0;kind=''
 for line in text.splitlines():
  if line.startswith(';TYPE:'):kind=line[6:]
  if line.startswith('G1 ') and kind.startswith('Support material') and (' X' in line or ' Y' in line):
   m=re.search(r'\bE(-?[\d.]+)',line)
   if m and float(m.group(1))>0:amount+=float(m.group(1))
 result['support_extrusion_filament_mm']=round(amount,2)
 if not support:assert amount==0,name
 target=P/(name+'.3mf')
 q=subprocess.run(common+['--export-3mf','--output',str(target),str(P/(name+'.stl'))],capture_output=True,text=True);assert q.returncode==0,(name,q.stdout,q.stderr)
 cfg=text.split('; prusaslicer_config = begin\n')[1].split('; prusaslicer_config = end')[0]
 with zipfile.ZipFile(target,'a',zipfile.ZIP_DEFLATED) as z:z.writestr('Metadata/Slic3r_PE.config','; generated by PrusaSlicer\n'+cfg)
 print(name+': '+str(result['estimated_time']),flush=True)
 return result

prior={}
if selected and (P/'slice-verification.json').exists():prior={r['part']:r for r in json.loads((P/'slice-verification.json').read_text())['parts']}
with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:rows=list(pool.map(check,parts))
prior.update({r['part']:r for r in rows})
for folder in ['main','modular']:shutil.copyfile(profile,P/folder/'mk3s-petg-06.ini')
aliases={'electronics-shell-left':'shell-left','electronics-base-left':'base-left','fit-coupon-left':'fit-coupon-left','fit-coupon-right':'fit-coupon-right'}
for dest,source in aliases.items():
 for ext in ['stl','3mf']:shutil.copyfile(P/'main'/f'{source}.{ext}',P/'modular'/f'{dest}.{ext}')
 src=prior['main/'+source];prior['modular/'+dest]={**src,'part':'modular/'+dest,'reused_from':'main/'+source,'byte_identical':True}
report={'revision':'logical_left_electronics','slicer':'PrusaSlicer','printer':'Prusa MK3S+','nozzle_mm':.6,'layer_mm':.3,'material':'PETG','parts':list(prior.values()),'limits':'Toolpaths and mesh/CAD checks are not a physical print, load or fit test.'}
(P/'slice-verification.json').write_text(json.dumps(report,indent=2)+'\n')
