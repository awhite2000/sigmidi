"""Audit and slice the two separate PETG inserts without support material."""
from pathlib import Path
import collections,hashlib,json,re,struct,subprocess,zipfile
P=Path(__file__).resolve().parent
SLICER='/Applications/Original Prusa Drivers/PrusaSlicer.app/Contents/MacOS/PrusaSlicer'
PROFILE=P.parent/'print/mk3s-petg-06.ini'
rows=[]
for name in ('usb-side-glue-insert','existing-pole-insert'):
 raw=(P/(name+'.stl')).read_bytes();n=struct.unpack_from('<I',raw,80)[0]
 assert len(raw)==84+50*n
 edges=collections.Counter();triangles=[];volume=0.;points=[]
 for i in range(n):
  xyz=struct.unpack_from('<12f',raw,84+50*i)[3:];v=[tuple(round(t,5) for t in xyz[j:j+3]) for j in (0,3,6)];triangles.append(v);points+=v
  for a,b in zip(v,v[1:]+v[:1]):edges[tuple(sorted((a,b)))]+=1
  a,b,c=v;volume+=(a[0]*(b[1]*c[2]-b[2]*c[1])+a[1]*(b[2]*c[0]-b[0]*c[2])+a[2]*(b[0]*c[1]-b[1]*c[0]))/6
 assert all(count==2 for count in edges.values()),name
 assert volume>0,name
 common=[SLICER,'--datadir','/tmp/sigmidi-nano-slicer','--load',str(PROFILE),'--no-support-material','--center','125,105','--threads','2']
 gc=Path('/tmp/sigmidi-'+name+'.gcode')
 r=subprocess.run(common+['--export-gcode','--output',str(gc),str(P/(name+'.stl'))],capture_output=True,text=True)
 Path('/tmp/sigmidi-'+name+'-slice.log').write_text(r.stdout+r.stderr);assert r.returncode==0,r.stderr
 text=gc.read_text();assert ';TYPE:Support material' not in text
 r=subprocess.run(common+['--export-3mf','--output',str(P/(name+'.3mf')),str(P/(name+'.stl'))],capture_output=True,text=True);assert r.returncode==0,r.stderr
 config=text.split('; prusaslicer_config = begin\n')[1].split('; prusaslicer_config = end')[0]
 with zipfile.ZipFile(P/(name+'.3mf'),'a',zipfile.ZIP_DEFLATED) as z:z.writestr('Metadata/Slic3r_PE.config','; generated by PrusaSlicer\n'+config)
 def value(pattern):
  m=re.search(pattern,text);return m.group(1) if m else None
 rows.append({'part':name,'triangles':n,'watertight_edges':True,'signed_volume_mm3':volume,'dimensions_mm':[round(max(p[k] for p in points)-min(p[k] for p in points),3) for k in range(3)],'STL_sha256':hashlib.sha256(raw).hexdigest(),'estimated_time':value(r'estimated printing time \(normal mode\) = (.*)'),'filament_g':value(r'filament used \[g\] = (.*)'),'support_material':False})
report={'printer':'Prusa MK3S+','material':'PETG','nozzle_mm':.6,'layer_mm':.3,'orientation':'Flat foot/bridge plate on bed; screw pilots up','parts':rows,'limits':'Nominal CAD and slicing checks. Adhesive strength, cable seating and small screw fit require physical testing.'}
(P/'print-verification.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report,indent=2))
