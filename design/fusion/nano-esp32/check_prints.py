"""Audit and slice the two current electronics bases with integral Nano posts."""
from pathlib import Path
import collections,hashlib,json,re,struct,subprocess,zipfile,shutil,math

P=Path(__file__).resolve().parent
ROOT=P.parents[2]
SLICER='/Applications/Original Prusa Drivers/PrusaSlicer.app/Contents/MacOS/PrusaSlicer'
PROFILE=P.parent/'print/mk3s-petg-06.ini'


def mesh(path,centers,plane):
 raw=path.read_bytes();n=struct.unpack_from('<I',raw,80)[0];assert len(raw)==84+50*n
 edges=collections.Counter();directions=collections.Counter();points=[];volume=0;segments=[];degenerate=0
 for i in range(n):
  xyz=struct.unpack_from('<12f',raw,84+50*i)[3:]
  v=[tuple(round(t,5) for t in xyz[j:j+3]) for j in (0,3,6)]
  points+=v
  for a,b in zip(v,v[1:]+v[:1]):
   edges[tuple(sorted((a,b)))]+=1;directions[(a,b)]+=1
  a,b,c=v
  volume+=(a[0]*(b[1]*c[2]-b[2]*c[1])+a[1]*(b[2]*c[0]-b[0]*c[2])+a[2]*(b[0]*c[1]-b[1]*c[0]))/6
  cross=[(b[1]-a[1])*(c[2]-a[2])-(b[2]-a[2])*(c[1]-a[1]),(b[2]-a[2])*(c[0]-a[0])-(b[0]-a[0])*(c[2]-a[2]),(b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0])]
  if sum(t*t for t in cross)<1e-16:degenerate+=1
  cut=[]
  for a,b in zip(v,v[1:]+v[:1]):
   if (a[2]<plane<b[2]) or (b[2]<plane<a[2]):
    t=(plane-a[2])/(b[2]-a[2]);cut.append((a[0]+t*(b[0]-a[0]),a[1]+t*(b[1]-a[1])))
  if len(cut)==2:segments.append(cut)
 boundary=sum(v==1 for v in edges.values());nonmanifold=sum(v>2 for v in edges.values())
 winding=sum(directions[(a,b)]!=1 or directions[(b,a)]!=1 for a,b in edges)
 assert boundary==nonmanifold==winding==degenerate==0,(path,boundary,nonmanifold,winding,degenerate)
 assert volume>0
 def distance(c,a,b):
  dx,dy=b[0]-a[0],b[1]-a[1];den=dx*dx+dy*dy
  if not den:return math.dist(c,a)
  t=max(0,min(1,((c[0]-a[0])*dx+(c[1]-a[1])*dy)/den))
  return math.hypot(c[0]-a[0]-t*dx,c[1]-a[1]-t*dy)
 probes=[]
 for center in centers:
  near=[s for s in segments if all(math.dist(p,center)<4.2 for p in s)]
  inner=[s for s in near if math.dist(((s[0][0]+s[1][0])/2,(s[0][1]+s[1][1])/2),center)<1.5]
  outer=[s for s in near if math.dist(((s[0][0]+s[1][0])/2,(s[0][1]+s[1][1])/2),center)>2]
  assert len(inner)>4 and len(outer)>4,(path,center,len(inner),len(outer))
  ir=min(distance(center,*s) for s in inner);orr=min(distance(center,*s) for s in outer)
  assert .74<ir<.81 and 2.95<orr<3.05,(path,center,ir,orr)
  probes.append({'center_print_XY_mm':center,'section_print_Z_mm':plane,'bore_min_radius_mm':ir,'outer_min_radius_mm':orr,'minimum_section_wall_mm':orr-max(math.dist(p,center) for s in inner for p in s)})
 return {'file':str(path.relative_to(ROOT)),'triangles':n,'bounds_mm':[[min(p[k] for p in points) for k in range(3)],[max(p[k] for p in points) for k in range(3)]],
         'boundary_edges':boundary,'nonmanifold_edges':nonmanifold,'inconsistent_winding_edges':winding,'degenerate_triangles':degenerate,'volume_mm3':volume,'STL_sha256':hashlib.sha256(raw).hexdigest(),'post_sections':probes}


def main():
 spec=json.loads((P/'mount-fit.json').read_text());assert not spec['component_face_down']
 assert spec['minimum_blind_web_above_vent_mm']>=2
 assert spec['post_minimum_radial_wall_mm']>=2
 rows=[];meshes=[]
 for name,folder,part,dx,originx,alias in [
  ('Left',P.parent/'mirrored/main','base-left',0,0,P.parent/'mirrored/modular/electronics-base-left'),
  ('Right',P.parent/'print','base-right',spec['checks'][2]['translation_X_mm'],193.9,P.parent/'modular/electronics-base')]:
  path=folder/(part+'.stl')
  centers=[[x+dx-originx,y+92] for x,y in spec['board_holes_XY_mm']]
  audit=mesh(path,centers,spec['PCB_bottom_Z_mm']+24-.7);meshes.append(audit)
  common=[SLICER,'--datadir','/tmp/sigmidi-direct-nano-slicer','--load',str(PROFILE),'--no-support-material','--center','125,105','--threads','2']
  gc=Path('/tmp/sigmidi-direct-nano-'+name.lower()+'.gcode')
  q=subprocess.run(common+['--export-gcode','--output',str(gc),str(path)],capture_output=True,text=True)
  Path('/tmp/sigmidi-direct-nano-'+name.lower()+'-slice.log').write_text(q.stdout+q.stderr)
  assert q.returncode==0,q.stderr
  text=gc.read_text();assert ';TYPE:Support material' not in text
  target=folder/(part+'.3mf')
  q=subprocess.run(common+['--export-3mf','--output',str(target),str(path)],capture_output=True,text=True);assert q.returncode==0,q.stderr
  config=text.split('; prusaslicer_config = begin\n')[1].split('; prusaslicer_config = end')[0]
  with zipfile.ZipFile(target,'a',zipfile.ZIP_DEFLATED) as z:z.writestr('Metadata/Slic3r_PE.config','; generated by PrusaSlicer\n'+config)
  for ext in ['.stl','.3mf']:shutil.copyfile(folder/(part+ext),alias.with_suffix(ext))
  def value(pattern):
   m=re.search(pattern,text);return m.group(1) if m else None
  row={'part':part,'slice_exit_code':0,'support_enabled':False,'STL_sha256':audit['STL_sha256'],'estimated_time':value(r'estimated printing time \(normal mode\) = (.*)'),
       'filament_g':value(r'filament used \[g\] = (.*)'),'support_extrusion_filament_mm':0,'post_section_checks':audit['post_sections'],'source_mesh':audit['file']}
  rows.append(row)
  print(name, row['estimated_time'],flush=True)
  # Current per-family mesh/slice indexes retain unchanged part records.
  if name=='Left':
   mf=P.parent/'mirrored/mesh-audit.json';old=json.loads(mf.read_text())
   for i,v in enumerate(old):
    if v['file']==audit['file']:old[i]={**audit}
   mf.write_text(json.dumps(old,indent=2)+'\n')
   sf=P.parent/'mirrored/slice-verification.json';d=json.loads(sf.read_text())
   for i,v in enumerate(d['parts']):
    if v['part'] in ['main/base-left','modular/electronics-base-left']:d['parts'][i]={**row,'part':v['part']}
   d['revision']=spec['revision'];sf.write_text(json.dumps(d,indent=2)+'\n')
  else:
   for folder2,name2 in [(folder,part),(P.parent/'modular','electronics-base')]:
    mf=folder2/'mesh-audit.json';old=json.loads(mf.read_text())
    for i,v in enumerate(old):
     if Path(v['file']).name==name2+'.stl':old[i]={**audit,'file':str((folder2/(name2+'.stl')).relative_to(ROOT))}
    mf.write_text(json.dumps(old,indent=2)+'\n')
    sf=folder2/'slice-verification.json';d=json.loads(sf.read_text())
    for i,v in enumerate(d['parts']):
     if v['part']==name2:d['parts'][i]={**row,'part':name2}
    d['revision']=spec['revision'];sf.write_text(json.dumps(d,indent=2)+'\n')
 report={'revision':spec['revision'],'printer':'Prusa MK3S+','material':'PETG','nozzle_mm':.6,'layer_mm':.3,
         'orientation':'Outside floor down; integral posts up','unique_meshes':meshes,'parts':rows,
         'support_material':False,'all_eight_post_sections_open_and_at_least_2mm_wall':all(p['minimum_section_wall_mm']>=2 for m in meshes for p in m['post_sections']),
         'minimum_blind_web_above_vent_mm':spec['minimum_blind_web_above_vent_mm'],'physical_print_tested':False,
         'limits':'Mesh, analytic wall and slicer checks do not establish actual screw retention, cable seating, print strength or thermal performance.'}
 assert report['all_eight_post_sections_open_and_at_least_2mm_wall']
 (P/'print-verification.json').write_text(json.dumps(report,indent=2)+'\n')


if __name__=='__main__':main()
