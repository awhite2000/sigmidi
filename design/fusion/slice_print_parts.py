"""Validate STL slicing and export editable 3MFs using installed Prusa presets."""
from pathlib import Path
import subprocess,json,re,concurrent.futures,zipfile,sys
exe='/Applications/Original Prusa Drivers/PrusaSlicer.app/Contents/MacOS/PrusaSlicer'
out=Path(__file__).resolve().parent/'print'
def check(name):
 support=name.startswith('shell-')
 common=[exe,'--datadir','/tmp/midi-slicer-check','--load',str(out/'mk3s-petg-06.ini'),'--support-material' if support else '--no-support-material','--center','125,105','--threads','2']
 log=Path('/tmp/midi-'+name+'.log');gcode=Path('/tmp/midi-'+name+'.gcode')
 r=subprocess.run(common+['--export-gcode','--output',str(gcode),str(out/(name+'.stl'))],capture_output=True,text=True)
 log.write_text(r.stdout+r.stderr)
 if r.returncode:raise RuntimeError(log.read_text())
 result={'part':name,'slice_exit_code':r.returncode,'support_enabled':support}
 text=gcode.read_text();match=re.search(r'estimated printing time \(normal mode\) = (.*)',text);result['estimated_time']=match.group(1) if match else None
 for pattern,label in [(r'filament used \[g\] = (.*)','filament_g'),(r'filament used \[mm\] = (.*)','filament_mm')]:
  m=re.search(pattern,text);result[label]=m.group(1) if m else None
 support_e=0;kind=''
 for line in text.splitlines():
  if line.startswith(';TYPE:'):kind=line[6:]
  if line.startswith('G1 ') and kind.startswith('Support material'):
   m=re.search(r'\bE(-?[\d.]+)',line)
   if m and float(m.group(1))>0 and (' X' in line or ' Y' in line):support_e+=float(m.group(1))
 result['support_extrusion_filament_mm']=round(support_e,2)
 r=subprocess.run(common+['--export-3mf','--output',str(out/(name+'.3mf')),str(out/(name+'.stl'))],capture_output=True,text=True)
 if r.returncode:raise RuntimeError(r.stdout+r.stderr)
 cfg=text.split('; prusaslicer_config = begin\n')[1].split('; prusaslicer_config = end')[0]
 with zipfile.ZipFile(out/(name+'.3mf'),'a',zipfile.ZIP_DEFLATED) as z:z.writestr('Metadata/Slic3r_PE.config','; generated by PrusaSlicer 2.9.6\n'+cfg)
 return result
all_names=['shell-left','shell-right','base-left','base-right','fit-coupon-left','fit-coupon-right']
names=sys.argv[1:] or all_names
if any(n not in all_names for n in names):raise ValueError('Unknown print part')
prior={}
if sys.argv[1:] and (out/'slice-verification.json').exists():
 prior={r['part']:r for r in json.loads((out/'slice-verification.json').read_text())['parts']}
with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:checked=list(pool.map(check,names))
prior.update({r['part']:r for r in checked})
results=[prior[n] for n in all_names if n in prior]
(out/'slice-verification.json').write_text(json.dumps({'slicer':'PrusaSlicer 2.9.6','printer':'MK3S+','nozzle_mm':.6,'material':'Generic PETG','layer_mm':.3,'parts':results,'limitations':'Slicing success is not a physical fit or load test. Small pilot holes require drilling and tapping. Support extrusion is parsed positive extrusion under support feature tags.'},indent=2))
print(json.dumps(results,indent=2))
