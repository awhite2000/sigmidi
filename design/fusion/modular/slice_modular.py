"""Slice the four new alternatives; reuse byte-identical right parts/coupons."""
from pathlib import Path
import concurrent.futures
import json
import re
import shutil
import subprocess
import zipfile
import sys
import hashlib

out=Path(__file__).resolve().parent
main=out.parent/'print'
exe='/Applications/Original Prusa Drivers/PrusaSlicer.app/Contents/MacOS/PrusaSlicer'
new_names=['pair-shell','pair-base','pair-shell-at-cap','left-cap','pair-shell-D','pair-shell-at-cap-C','pair-shell-at-cap-E']
selected=[] if sys.argv[1:]==['--reuse-only'] else (sys.argv[1:] or new_names)
assert set(selected)<=set(new_names), 'Select new print part names or --reuse-only'
reuse={'electronics-shell':'shell-right','electronics-base':'base-right','fit-coupon-left':'fit-coupon-left','fit-coupon-right':'fit-coupon-right'}
shutil.copyfile(main/'mk3s-petg-06.ini',out/'mk3s-petg-06.ini')
for new,old in reuse.items():
    for ext in ['stl','3mf']:shutil.copyfile(main/f'{old}.{ext}',out/f'{new}.{ext}')


def check(name):
    support='shell' in name or name=='left-cap'
    common=[exe,'--datadir','/tmp/midi-modular-slicer','--load',str(out/'mk3s-petg-06.ini'),
            '--support-material' if support else '--no-support-material','--center','125,105','--threads','2']
    gcode=Path('/tmp/midi-modular-'+name+'.gcode')
    process=subprocess.run(common+['--export-gcode','--output',str(gcode),str(out/(name+'.stl'))],capture_output=True,text=True)
    Path('/tmp/midi-modular-'+name+'.log').write_text(process.stdout+process.stderr)
    if process.returncode:raise RuntimeError(process.stdout+process.stderr)
    text=gcode.read_text();result={'part':name,'slice_exit_code':0,'support_enabled':support}
    for pattern,label in [(r'estimated printing time \(normal mode\) = (.*)','estimated_time'),(r'filament used \[g\] = (.*)','filament_g'),(r'filament used \[mm\] = (.*)','filament_mm')]:
        m=re.search(pattern,text);result[label]=m.group(1) if m else None
    amount=0;kind=''
    for line in text.splitlines():
        if line.startswith(';TYPE:'):kind=line[6:]
        if line.startswith('G1 ') and kind.startswith('Support material') and (' X' in line or ' Y' in line):
            m=re.search(r'\bE(-?[\d.]+)',line)
            if m and float(m.group(1))>0:amount+=float(m.group(1))
    result['support_extrusion_filament_mm']=round(amount,2)
    process=subprocess.run(common+['--export-3mf','--output',str(out/(name+'.3mf')),str(out/(name+'.stl'))],capture_output=True,text=True)
    if process.returncode:raise RuntimeError(process.stdout+process.stderr)
    cfg=text.split('; prusaslicer_config = begin\n')[1].split('; prusaslicer_config = end')[0]
    with zipfile.ZipFile(out/(name+'.3mf'),'a',zipfile.ZIP_DEFLATED) as z:z.writestr('Metadata/Slic3r_PE.config','; generated by PrusaSlicer\n'+cfg)
    return result


previous={r['part']:r for r in json.loads((out/'slice-verification.json').read_text())['parts']} if (out/'slice-verification.json').exists() else {}
prior_hashes=json.loads((out/'sliced-stl-hashes.json').read_text()) if (out/'sliced-stl-hashes.json').exists() else {}
for n in new_names:
    if n not in selected:
        assert n in previous and hashlib.sha256((out/(n+'.stl')).read_bytes()).hexdigest()==prior_hashes.get(n+'.stl'), 'Reslice modified part '+n
with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
    changed={r['part']:r for r in pool.map(check,selected)}
results=[changed[n] if n in changed else previous[n] for n in new_names]
prior={r['part']:r for r in json.loads((main/'slice-verification.json').read_text())['parts']}
for new,old in reuse.items():
    r=prior[old].copy();r.update({'part':new,'reused_from_main':old,'STL_and_3MF_byte_identical':True});results.append(r)
report={'printer':'Prusa MK3S+','material':'Generic PETG','nozzle_mm':.6,'layer_mm':.3,'parts':results,
        'limits':'Slicing and mesh validation are not physical tolerance or load tests. Main right parts and coupons are copied byte-identically from their verified package.'}
(out/'slice-verification.json').write_text(json.dumps(report,indent=2))
(out/'sliced-stl-hashes.json').write_text(json.dumps({n+'.stl':hashlib.sha256((out/(n+'.stl')).read_bytes()).hexdigest() for n in new_names+list(reuse)},indent=2))
print(json.dumps([r for r in results if r['part'] in selected],indent=2))
