#!/usr/bin/env python3
"""Trace the supplied ink outline without redrawing it. Requires Pillow."""
from pathlib import Path
import hashlib
import json
import math
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'design/branding'


def simplify(points, tolerance=0.7):
    if len(points) < 3:
        return points
    ax, ay = points[0]
    bx, by = points[-1]
    dx, dy = bx - ax, by - ay
    length = dx * dx + dy * dy
    distances = []
    for x, y in points[1:-1]:
        t = max(0, min(1, ((x - ax) * dx + (y - ay) * dy) / length)) if length else 0
        distances.append(math.hypot(x - ax - t * dx, y - ay - t * dy))
    maximum = max(distances)
    if maximum <= tolerance:
        return [points[0], points[-1]]
    split = distances.index(maximum) + 1
    return simplify(points[:split + 1], tolerance)[:-1] + simplify(points[split:], tolerance)


def main():
    source = OUT / 'logotype-original.png'
    original = Image.open(source).convert('RGB')
    # The supplied main ink is RGB(102,102,153); its pale shadow is separate.
    # Half-coverage threshold keeps the main outline and removes the optional shadow.
    mask = original.getchannel('R').point(lambda value: 255 if value < 179 else 0)
    bounds = mask.getbbox()
    mask = mask.crop(bounds)
    width, height = mask.size
    pixels = mask.tobytes()
    edges = {}
    def edge(start, end):
        edges.setdefault(start, []).append(end)
    for y in range(height):
        for x in range(width):
            i = y * width + x
            if not pixels[i]:
                continue
            if y == 0 or not pixels[i - width]: edge((x, y), (x + 1, y))
            if x == width - 1 or not pixels[i + 1]: edge((x + 1, y), (x + 1, y + 1))
            if y == height - 1 or not pixels[i + width]: edge((x + 1, y + 1), (x, y + 1))
            if x == 0 or not pixels[i - 1]: edge((x, y + 1), (x, y))
    contours = []
    while edges:
        start = next(iter(edges))
        point = start
        contour = [start]
        while True:
            following = edges[point].pop()
            if not edges[point]: del edges[point]
            point = following
            contour.append(point)
            if point == start: break
        if len(contour) > 8:
            split = len(contour) // 2
            contours.append(simplify(contour[:split + 1])[:-1] + simplify(contour[split:]))
    path = ' '.join('M' + ' L'.join(f'{x} {y}' for x, y in contour[:-1]) + ' Z' for contour in contours)
    colors = {'sigmidi-mark': '#205442', 'sigmidi-mark-light': '#eaf2ed', 'sigmidi-mark-original': '#666699'}
    for name, color in colors.items():
        svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="-24 -24 {width + 48} {height + 48}">'
               f'<title>SIGMIDI logotype</title><path fill="{color}" fill-rule="evenodd" d="{path}"/></svg>\n')
        (OUT / f'{name}.svg').write_text(svg)
        rgba = Image.new('RGBA', mask.size, color)
        rgba.putalpha(mask)
        rgba.thumbnail((512, 512), Image.Resampling.LANCZOS)
        rgba.save(OUT / f'{name}.png')
    # Shared source geometry for the embedded editor and browser favicon.
    light = (OUT / 'sigmidi-mark-light.svg').read_text()
    inline = light.replace('<svg ', '<svg class="brand-mark" aria-hidden="true" focusable="false" ', 1)
    web = ROOT / 'web/index.html'
    text = web.read_text()
    marker = '<!-- SIGMIDI_LOGOTYPE -->'
    end_marker = '<!-- /SIGMIDI_LOGOTYPE -->'
    if marker in text:
        start = text.index(marker)
        end = text.index(end_marker, start) + len(end_marker)
        text = text[:start] + marker + inline.strip() + end_marker + text[end:]
    else:
        text = text.replace('<h1>', '<h1>' + marker + inline.strip() + end_marker, 1)
    web.write_text(text)
    (ROOT / 'flasher/icon.svg').write_text((OUT / 'sigmidi-mark.svg').read_text())
    # Alpha bitmap for the 280x240 production renderer, keeping the same aspect ratio.
    lcd = Image.new('L', (24, 20), 0)
    small = mask.copy()
    small.thumbnail((24, 20), Image.Resampling.LANCZOS)
    lcd.paste(small, ((24 - small.width) // 2, (20 - small.height) // 2))
    values = list(lcd.tobytes())
    rows = ['    ' + ','.join(map(str, values[i:i + 24])) for i in range(0, len(values), 24)]
    (ROOT / 'src/logo.hpp').write_text('// Generated by scripts/prepare_logotype.py from the supplied mark.\n#pragma once\n#include <cstdint>\nnamespace foot {\ninline constexpr int LogoWidth = 24, LogoHeight = 20;\ninline constexpr uint8_t LogoAlpha[] = {\n' + ',\n'.join(rows) + '\n};\n} // namespace foot\n')
    report = dict(source='logotype-original.png', source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                  main_ink_rgb=[102, 102, 153], source_ink_bounds_px=bounds, vector_contours=len(contours),
                  vector_points=sum(len(c) for c in contours), maximum_trace_simplification_px=0.7,
                  shadow_removed=True, geometry='Main ink boundary traced; no rotation, skew or nonuniform scaling.',
                  SVG_sha256={p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in OUT.glob('*.svg')})
    (OUT / 'logotype-provenance.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
